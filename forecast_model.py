"""
forecast_model.py - Random Forest traffic forecaster.

For every directed road the model predicts the LOAD RATIO (cars on the road / road capacity)
1, 2, 3 and 4 hours into the future.  One RandomForestRegressor with 4 outputs does all four
horizons at once.

Inputs (features) for each road at the current hour
  * time of day (sin / cos)
  * current load and the load 1, 2 and 3 hours ago
  * average load of the roads feeding into it (upstream) and leaving it (downstream)
  * share of cars on the road that are (almost) not moving
  * road length and capacity
  * the nearest KNOWN accident: hops away, does the road lead toward it, hours until it
    starts, is it active, severity, hours it will still last
  * the driver-response setting (do drivers act on the 4-hour warning or only react?)   ("known" = the 4-hour warning was issued)

The training data is generated by running engine.py headlessly for many simulated days
with random accidents and random demand (see train_model.py).
"""
import os
import json
import math
import numpy as np

import engine as eng_mod

MODEL_PATH = os.path.join(os.path.dirname(__file__), "models", "rf_traffic.joblib")
FEATURES = ["hod_sin", "hod_cos", "load", "lag1", "lag2", "lag3", "up_load", "down_load",
            "stopped_frac", "road_len", "road_cap", "acc_dist", "acc_toward", "acc_eta", "acc_active", "acc_sev", "acc_left", "early_policy"]
NO_ACC_DIST = 7
NO_ACC_ETA = 9.0


def build_features(eng):
    """Feature matrix (n_roads x n_features) describing the network right now."""
    net = eng.net
    E = len(net.edges)
    loads = eng.loads()
    hist = list(eng.hist)                                   # oldest ... newest (= 1 hour ago)

    def lag(k):
        return hist[-k] if len(hist) >= k else loads

    l1, l2, l3 = lag(1), lag(2), lag(3)
    ang = 2 * math.pi * (eng.t % 24) / 24
    s, c = math.sin(ang), math.cos(ang)
    known = [a for a in eng.accidents if a["status"] in ("warning", "active")]
    policy = 1.0 if eng.mode == "early" else 0.0        # do drivers act on the 4-hour warning?

    X = np.zeros((E, len(FEATURES)), dtype=np.float32)
    for i, e in enumerate(net.edges):
        vs = eng.veh[i]
        up = [loads[j] for j in net.up_edges[i]]
        down = [loads[j] for j in net.down_edges[i]]
        stopped = (sum(1 for v in vs if v.vel * e.L < 0.1) / len(vs)) if vs else 0.0
        dist, toward, eta, active, sev, left = NO_ACC_DIST, 0.0, NO_ACC_ETA, 0.0, 0.0, 0.0
        for a in known:
            d_to = min(net.hops[e.to][m] for m in a["nodes"])
            d_from = min(net.hops[e.frm][m] for m in a["nodes"])
            d = min(min(d_to, d_from), NO_ACC_DIST - 1)
            if d < dist or (d == dist and a["start"] < eta + eng.t):
                dist = d
                toward = 1.0 if d_to < d_from else 0.0      # road leads TOWARD the accident (queue builds up)
                eta = max(0.0, min(a["start"] - eng.t, NO_ACC_ETA - 1))
                active = 1.0 if eng.t >= a["start"] else 0.0
                sev = a["sev"]
                left = max(0.0, min(a["end"] - max(eng.t, a["start"]), 8.0))
        X[i] = [s, c, loads[i], l1[i], l2[i], l3[i],
                sum(up) / len(up) if up else loads[i], sum(down) / len(down) if down else loads[i],
                stopped, e.L, e.cap, dist, toward, eta, active, sev, left, policy]
    return X


class Forecaster:
    """Loads the trained Random Forest and predicts the next 4 hours for every road."""

    def __init__(self, path=MODEL_PATH):
        import joblib
        import sklearn
        blob = joblib.load(path)
        if blob.get("sklearn") != sklearn.__version__:
            raise RuntimeError(f"model was trained with scikit-learn {blob.get('sklearn')}, "
                               f"you have {sklearn.__version__} - please retrain")
        self.model = blob["model"]
        self.model.n_jobs = 1
        self.metrics = blob.get("metrics", {})

    def predict(self, eng):
        Y = self.model.predict(build_features(eng))         # (n_roads, 4)
        return np.clip(Y, 0.0, 1.3)


def load_metrics(path=MODEL_PATH):
    p = path.replace(".joblib", "_metrics.json")
    if os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    return None
